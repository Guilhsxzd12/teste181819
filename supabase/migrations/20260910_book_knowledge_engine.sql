create or replace function public.trigger_knowledge_worker(p_limit integer default 50)
returns bigint language plpgsql security definer set search_path=public,extensions,vault,net as $$
declare request_id bigint; secret_value text;
begin
  select decrypted_secret into secret_value from vault.decrypted_secrets where name='kindle_knowledge_cron_secret' limit 1;
  if secret_value is null then raise exception 'knowledge cron secret missing'; end if;
  select net.http_post(
    url:='https://fsnpdtuzkayxngeltqdl.supabase.co/functions/v1/knowledge-worker',
    headers:=jsonb_build_object('Content-Type','application/json','X-Knowledge-Secret',secret_value),
    body:=jsonb_build_object('limit',least(greatest(coalesce(p_limit,50),1),100)),
    timeout_milliseconds:=120000
  ) into request_id;
  return request_id;
end;
$$;
revoke all on function public.trigger_knowledge_worker(integer) from public,anon,authenticated;
grant execute on function public.trigger_knowledge_worker(integer) to service_role;

do $$ declare r record; begin
  for r in select jobid from cron.job where jobname='kindle-knowledge-worker' loop perform cron.unschedule(r.jobid); end loop;
end $$;
select cron.schedule('kindle-knowledge-worker','*/10 * * * *',$$select public.trigger_knowledge_worker(50);$$);
